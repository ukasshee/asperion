let currentLang = localStorage.getItem("asperion-lang") || "pl";
const storedTheme = localStorage.getItem("asperion-theme-v2");
let currentTheme = storedTheme === "dark" || storedTheme === "contrast" ? "contrast" : "light";

function updateThemeLabel() {
  const themeButton = document.querySelector(".theme-toggle");
  if (!themeButton) return;
  const isContrast = currentTheme === "contrast";
  const label = isContrast ? translations[currentLang].contrastOff : translations[currentLang].contrastOn;
  themeButton.setAttribute("aria-label", label);
  themeButton.setAttribute("title", label);
  themeButton.setAttribute("aria-pressed", String(isContrast));
}

function setTheme(theme, persist = true) {
  currentTheme = theme;
  document.documentElement.dataset.theme = theme;
  if (persist) localStorage.setItem("asperion-theme-v2", theme);
  document.querySelector('meta[name="theme-color"]').content = theme === "contrast" ? "#000000" : "#fbf8f3";
  updateThemeLabel();
}

function setLanguage(lang, persist = true) {
  currentLang = lang;
  if (persist) localStorage.setItem("asperion-lang", lang);
  document.documentElement.lang = lang;
  document.title = translations[lang].title;
  document.querySelector('meta[name="description"]').content = translations[lang].description;
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", translations[lang].title);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", translations[lang].description);
  document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", translations[lang].title);
  document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", translations[lang].description);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = translations[lang][node.dataset.i18n];
    if (value) node.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = translations[lang][node.dataset.i18nAlt];
    if (value) node.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = translations[lang][node.dataset.i18nAria];
    if (value) node.setAttribute("aria-label", value);
  });

  const languageButton = document.querySelector("[data-language-toggle]");
  if (languageButton) {
    const label = lang === "pl" ? translations.pl.languageToEnglish : translations.en.languageToPolish;
    languageButton.querySelector("img").src = lang === "pl" ? "flag-gb.svg" : "flag-pl.svg";
    languageButton.setAttribute("aria-label", label);
    languageButton.setAttribute("title", label);
  }
  updateMenuLabel();
  updateThemeLabel();
  document.dispatchEvent(new CustomEvent("asperion:language", { detail: { lang } }));
}

document.querySelector("[data-language-toggle]")?.addEventListener("click", () => {
  setLanguage(currentLang === "pl" ? "en" : "pl");
});

document.querySelector(".theme-toggle")?.addEventListener("click", () => {
  setTheme(currentTheme === "contrast" ? "light" : "contrast");
});

const toggle = document.querySelector(".menu-toggle");
const links = document.querySelector(".nav-links");

function updateMenuLabel() {
  if (!toggle) return;
  const expanded = toggle.getAttribute("aria-expanded") === "true";
  toggle.setAttribute("aria-label", translations[currentLang][expanded ? "menuClose" : "menuOpen"]);
}

function closeMobileMenu() {
  toggle?.setAttribute("aria-expanded", "false");
  links?.classList.remove("open");
  document.body.classList.remove("menu-open");
  updateMenuLabel();
}

toggle?.addEventListener("click", () => {
  const expanded = toggle.getAttribute("aria-expanded") === "true";
  toggle.setAttribute("aria-expanded", String(!expanded));
  links.classList.toggle("open", !expanded);
  document.body.classList.toggle("menu-open", !expanded);
  updateMenuLabel();
});

document.querySelectorAll('.nav-links a').forEach((link) => link.addEventListener("click", () => {
  closeMobileMenu();
}));

document.addEventListener("pointerdown", (event) => {
  if (toggle?.getAttribute("aria-expanded") !== "true") return;
  if (links?.contains(event.target) || toggle.contains(event.target)) return;
  closeMobileMenu();
});

document.addEventListener("keydown", (event) => {
  if (event.key !== "Escape" || toggle?.getAttribute("aria-expanded") !== "true") return;
  closeMobileMenu();
  toggle.focus();
});

function signalLead(type) {
  window.dispatchEvent(new CustomEvent("asperion:lead", { detail: { type } }));
}

document.querySelector("[data-call-button]")?.addEventListener("click", (event) => {
  signalLead("phone_click");
  const mobileUserAgent = navigator.userAgentData?.mobile;
  const isPhone = typeof mobileUserAgent === "boolean"
    ? mobileUserAgent
    : /Android.+Mobile|iPhone|iPod|Windows Phone|webOS/i.test(navigator.userAgent);

  if (isPhone) return;

  event.preventDefault();
  const button = event.currentTarget;
  const number = document.querySelector("#desktop-phone-number");
  number.hidden = false;
  button.setAttribute("aria-expanded", "true");
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.14 });
document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

document.querySelector("#contact-form")?.addEventListener("submit", async (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const status = form.querySelector(".form-status");
  const submit = form.querySelector('button[type="submit"]');
  const data = new FormData(form);

  status.textContent = translations[currentLang].formSending;
  submit.disabled = true;

  try {
    const response = await fetch("/api/contact", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        name: data.get("name"),
        email: data.get("email"),
        phone: data.get("phone"),
        topic: data.get("topic"),
        message: data.get("message"),
        website: data.get("website"),
        consent: data.get("consent") === "on",
        lang: currentLang
      })
    });
    const result = await response.json().catch(() => ({}));
    if (!response.ok) {
      const key = result.code === "rate_limit" ? "formRateLimit" : "formError";
      throw new Error(key);
    }
    status.textContent = translations[currentLang].formSuccess;
    form.reset();
    signalLead("form_submit");
  } catch (error) {
    status.textContent = translations[currentLang][error.message] || translations[currentLang].formError;
  } finally {
    submit.disabled = false;
  }
});

document.querySelector("#year").textContent = new Date().getFullYear();
setTheme(currentTheme, false);
setLanguage(currentLang, false);
